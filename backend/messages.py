def checklist_message(items: list[str]) -> str:
    checklist = "\n".join(f"{number}. {item}" for number, item in enumerate(items, 1))
    return f"Чек-лист для построения:\n{checklist}\n\n{AFTER_CHECKLIST}"


def input_error(code: str, detail: str) -> str:
    action = ERROR_ACTIONS["INVALID_FORMAT"] if code == "INVALID_FORMAT" else (
        "Попробуй снова или проверь, что FastAPI запущен."
    )
    return f"Не удалось обработать размеры ({code}).\nПричина: {detail}\n{action}"


def file_error(code: str, detail: str) -> str:
    return (
        f"Не удалось обработать файл ({code}).\n"
        f"Причина: {detail}\n"
        f"Что делать: {ERROR_ACTIONS.get(code, ERROR_ACTIONS['INTERNAL_ERROR'])}\n"
        "Повторить: /new или загрузи другой STL."
    )
